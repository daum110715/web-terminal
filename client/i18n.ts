export type Language = "auto" | "zh" | "en";
export const LANGUAGE_KEY = "web-terminal:language";

const chosen = recall(LANGUAGE_KEY);
export const language: "zh" | "en" =
  chosen === "zh" || chosen === "en" ? chosen : navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
const words = language === "zh" ? zh : en;

export function t(key: keyof typeof en, values: Record<string, string | number> = {}): string {
  return words[key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}
